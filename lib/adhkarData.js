function toEveningArabic(arabic) {
  return arabic
    .replace(/أَصْبَحْنَا/g, "أَمْسَيْنَا")
    .replace(/أَصْبَحْتُ/g, "أَمْسَيْتُ")
    .replace(/هَذَا الْيَوْمِ/g, "هَذِهِ اللَّيْلَةِ")
    .replace(/الْيَوْمِ/g, "اللَّيْلَةِ")
}

