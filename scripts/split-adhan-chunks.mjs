/**
 * Split each full Adhan MP3 at pauses between phrases.
 * Each piece stays under 28 seconds. Lock-screen wav/caf clips are left alone.
 *
 * Usage: node scripts/split-adhan-chunks.mjs
 */
import { spawnSync } from "node:child_process"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const dir = path.join(root, "assets/adhan")
const MAX_CHUNK = 27.5
const MIN_PAUSE = 0.28

const STEMS = [
  "adhan_alafasy",
  "adhan_alafasy_fajr",
  "adhan_abdulbasit",
  "adhan_abdulbasit_fajr",
  "adhan_trablsy",
  "adhan_trablsy_fajr",
  "adhan_mulla",
  "adhan_mulla_fajr",
  "adhan_bokhari",
  "adhan_bokhari_fajr",
  "adhan_ozcan",
  "adhan_ozcan_fajr",
]

function run(cmd, args) {
  const result = spawnSync(cmd, args, { encoding: "utf8" })
  if (result.status !== 0 && cmd !== "ffmpeg") {
    throw new Error(result.stderr || `${cmd} failed`)
  }
  return `${result.stdout || ""}\n${result.stderr || ""}`
}

function durationOf(file) {
  const out = run("ffprobe", [
    "-v", "error",
    "-show_entries", "format=duration",
    "-of", "csv=p=0",
    file,
  ])
  return Number(out.trim())
}

function silences(file) {
  const output = run("ffmpeg", ["-i", file, "-af", `silencedetect=noise=-30dB:d=${MIN_PAUSE}`, "-f", "null", "-"])
  const ranges = []
  let start = null
  for (const line of output.split("\n")) {
    const began = line.match(/silence_start:\s*([0-9.]+)/)
    if (began) start = Number(began[1])
    const ended = line.match(/silence_end:\s*([0-9.]+)/)
    if (ended && start != null) {
      ranges.push({ start, end: Number(ended[1]) })
      start = null
    }
  }
  return ranges
}

/** @returns {{ start: number, end: number }[]} */
function planChunks(duration, pauses) {
  const chunks = []
  let cursor = 0
  while (cursor < duration - 0.35) {
    const windowEnd = Math.min(cursor + MAX_CHUNK, duration)
    const pause = pauses.find(item => item.start > cursor + 8 && item.start <= windowEnd + 0.05)
    let end = pause ? Math.min(pause.start, duration) : windowEnd
    if (end - cursor < 8 && windowEnd < duration) end = windowEnd
    if (end <= cursor) end = Math.min(cursor + MAX_CHUNK, duration)
    chunks.push({ start: round(cursor), end: round(end) })
    if (pause && end >= pause.start - 0.05) cursor = pause.end
    else cursor = end
  }
  return chunks.filter(chunk => chunk.end - chunk.start >= 0.8)
}

function round(n) {
  return Math.round(n * 1000) / 1000
}

function exportChunk(mp3, chunk, dest) {
  const tmp = path.join(os.tmpdir(), `adhan-chunk-${process.pid}.wav`)
  const length = Math.max(0.5, chunk.end - chunk.start)
  run("ffmpeg", [
    "-y",
    "-ss", String(chunk.start),
    "-t", String(length),
    "-i", mp3,
    "-ac", "1",
    "-ar", "22050",
    "-c:a", "pcm_s16le",
    tmp,
  ])
  run("afconvert", [tmp, dest, "-f", "caff", "-d", "LEI16@22050", "-c", "1"])
  fs.rmSync(tmp, { force: true })
  const info = run("afinfo", [dest])
  const match = info.match(/estimated duration:\s*([0-9.]+)/)
  const seconds = match ? Number(match[1]) : length
  if (seconds >= 30) throw new Error(`${dest} is ${seconds}s`)
  return seconds
}

function clearOldChunks() {
  for (const name of fs.readdirSync(dir)) {
    if (/^adhan_.+_\d{2}\.caf$/.test(name)) fs.rmSync(path.join(dir, name))
  }
}

clearOldChunks()
const catalog = {}

for (const stem of STEMS) {
  const mp3 = path.join(dir, `${stem}.mp3`)
  const duration = durationOf(mp3)
  const pauses = silences(mp3)
  const chunks = planChunks(duration, pauses)
  const key = stem.replace(/^adhan_/, "")
  catalog[key] = {
    duration: round(duration),
    chunks: chunks.map((chunk, index) => {
      const file = `${stem}_${String(index).padStart(2, "0")}.caf`
      const seconds = exportChunk(mp3, chunk, path.join(dir, file))
      console.log(`${file}  offset ${chunk.start}s  length ${seconds.toFixed(2)}s`)
      return { file, offset: chunk.start }
    }),
  }
}

const out = `/** Generated by scripts/split-adhan-chunks.mjs. Do not edit by hand. */\nexport const ADHAN_CHUNK_LISTS = ${JSON.stringify(catalog, null, 2)} as const\n`
fs.writeFileSync(path.join(root, "lib/adhanChunks.generated.ts"), out)

const appJsonPath = path.join(root, "app.json")
const appJson = JSON.parse(fs.readFileSync(appJsonPath, "utf8"))
const chunkPaths = Object.values(catalog).flatMap(entry =>
  entry.chunks.map(chunk => `./assets/adhan/${chunk.file}`)
)
function mergeSounds(list) {
  const kept = list.filter(item => !/adhan_.+_\d{2}\.caf$/.test(item))
  return [...kept, ...chunkPaths]
}
appJson.expo.notification.sounds = mergeSounds(appJson.expo.notification.sounds)
const plugin = appJson.expo.plugins.find(item => Array.isArray(item) && item[0] === "expo-notifications")
plugin[1].sounds = mergeSounds(plugin[1].sounds)
fs.writeFileSync(appJsonPath, `${JSON.stringify(appJson, null, 2)}\n`)
console.log(`Wrote ${chunkPaths.length} chunks`)
